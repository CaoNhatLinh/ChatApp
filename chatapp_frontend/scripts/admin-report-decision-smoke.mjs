import assert from 'node:assert/strict';
import { readFile } from 'node:fs/promises';
import ts from 'typescript';

const source = await readFile('src/features/admin/model/report-decision.ts', 'utf8');
const compiled = ts.transpileModule(source, { compilerOptions: { module: ts.ModuleKind.ES2022, target: ts.ScriptTarget.ES2022 } }).outputText;
const { reportIdentity, canDecideReport, decisionError, hasReportDraft, filterAdminReports, reportMatchesDraft } = await import(`data:text/javascript;base64,${Buffer.from(compiled).toString('base64')}`);
const labelSource = await readFile('src/features/admin/components/report-labels.ts', 'utf8');
const labelCode = ts.transpileModule(labelSource, { compilerOptions: { module: ts.ModuleKind.ES2022 } }).outputText;
const { reportReasonLabel, reportTargetLabel, reportStateLabel } = await import(`data:text/javascript;base64,${Buffer.from(labelCode).toString('base64')}`);
const report = { reportId: 'one', createdAtKey: '2026-10-23T00:00:00Z', reportDay: '2026-10-23', status: 'OPEN', reasonCode: 'SPAM', description: 'Quấy rối, gửi link liên tục.' };
const draft = { report, nextStatus: 'RESOLVED', reason: '', resolutionCode: '' };
assert.notEqual(reportIdentity(report), reportIdentity({ ...report, createdAtKey: 'other' }));
assert.equal(canDecideReport(report, 'IN_REVIEW'), true);
assert.equal(canDecideReport({ ...report, status: 'IN_REVIEW' }, 'IN_REVIEW'), false);
assert.equal(canDecideReport({ ...report, status: 'RESOLVED' }, 'DISMISSED'), false);
assert.equal(canDecideReport(report, 'OPEN'), false);
assert.equal(decisionError(draft), 'reason');
assert.equal(decisionError({ ...draft, reason: 'evidence' }), 'resolutionCode');
assert.equal(decisionError({ ...draft, reason: 'evidence', resolutionCode: 'CONFIRMED' }), null);
assert.equal(decisionError({ ...draft, nextStatus: 'IN_REVIEW', reason: 'review' }), null);
assert.equal(decisionError({ ...draft, reason: 'x'.repeat(501), resolutionCode: 'OK' }), 'reason');
assert.equal(hasReportDraft(draft), false);
assert.equal(hasReportDraft({ ...draft, reason: '  evidence ' }), true);
assert.equal(reportMatchesDraft([report], draft), true);
assert.equal(reportMatchesDraft([{ ...report, status: 'IN_REVIEW' }], draft), false);
assert.equal(reportMatchesDraft([], draft), false);
assert.equal(filterAdminReports([report], 'quay roi', () => '')[0], report);
assert.equal(filterAdminReports([report], '  spam ', () => '').length, 1);
assert.equal(filterAdminReports([report], 'missing', () => '').length, 0);
assert.equal(report.status, 'OPEN', 'model operations never mutate loaded server facts');
assert.equal(reportReasonLabel('SPAM', 'vi'), 'Spam hoặc lừa đảo');
assert.equal(reportReasonLabel('CUSTOM_REASON', 'en'), 'CUSTOM_REASON');
assert.equal(reportTargetLabel('MESSAGE', 'en'), 'Message');
assert.equal(reportStateLabel('IN_REVIEW', 'en'), 'In review');
assert.equal(filterAdminReports([report], 'scams', entry => reportReasonLabel(entry.reasonCode, 'en')).length, 1);
assert.equal(filterAdminReports([report], 'lua dao', entry => reportReasonLabel(entry.reasonCode, 'vi')).length, 1);
console.log('PASS: 25 report decision/search/label checks');
